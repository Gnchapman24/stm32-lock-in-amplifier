"""Run every Phase 0 experiment and write results/phase0/SUMMARY.md.

    cd sim
    python -m experiments.run_all
"""
import importlib
import sys
import time

from experiments.common import OUT

EXPERIMENTS = [
    ("e1_enbw", "E1 — Output noise vs ENBW", "e1_enbw"),
    ("e2_settling", "E2 — Step response / settling", "e2_settling"),
    ("e3_processing_gain", "E3 — Processing gain", "e3_processing_gain"),
    ("e4_sync_filter", "E4 — 2f ripple and the sync filter", "e4_sync_filter"),
    ("e5_dead_band", "E5 — IIR dead band", "e5_dead_band"),
    ("e6_q31_error", "E6 — Q31 vs float error", "e6_q31_error"),
    ("e7_clipping", "E7 — Clipping and dynamic reserve", "e7_clipping"),
    ("e8_bode", "E8 — Simulated Bode analyzer + through calibration", "e8_bode"),
]


def main() -> int:
    rows, figs = [], []
    for mod, title, fig in EXPERIMENTS:
        t0 = time.perf_counter()
        print(f"{title} ...", end=" ", flush=True)
        rows += importlib.import_module(f"experiments.{mod}").run()
        print(f"{time.perf_counter() - t0:.1f} s")
        figs.append((title, fig))
    figs.insert(3, ("E3 — Before / after at −40 dB input SNR", "e3_before_after"))

    n_fail = sum(r.ok is False for r in rows)
    lines = [
        "# Phase 0 — Simulation Results",
        "",
        "Generated by `python -m experiments.run_all` (in `sim/`). Do not edit by hand.",
        "",
        f"**{sum(r.ok is True for r in rows)} checks passed, {n_fail} failed, "
        f"{sum(r.ok is None for r in rows)} informational.**",
        "",
        "| Exp | Check | Theory / prediction | Measured | Result |",
        "|---|---|---|---|---|",
    ]
    lines += [f"| {r.exp} | {r.item} | {r.theory} | {r.measured} | {r.verdict} |" for r in rows]
    lines += ["", "## Figures", ""]
    for title, fig in figs:
        lines += [f"### {title}", "", f"![{title}]({fig}.png)", ""]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "SUMMARY.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"\nwrote {OUT / 'SUMMARY.md'}  ({n_fail} failed)")
    return 1 if n_fail else 0


if __name__ == "__main__":
    sys.exit(main())
